const step = (text) =>
  new Paragraph({ numbering: { reference: "steps", level: 0 }, children: runs(text), spacing: { after: 40, line: 300 } });
const formula = (text) =>
  new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 80, after: 120 },
    children: [new TextRun({ text, italics: true })],
  });
const note = (text) =>
  new Paragraph({ children: runs(text, { size: 20, italics: true, color: "555555" }), spacing: { after: 80 } });

const border = { style: BorderStyle.SINGLE, size: 4, color: "808080" };
